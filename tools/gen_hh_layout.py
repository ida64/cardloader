#!/usr/bin/env python3
"""Emit hh_payload.h and hookhost.bin from build/hookhost.elf.

The payload is linked at VA 0 with page-aligned sections, so the flat binary
offset equals the VA. The `ro` patch maps the whole image and sets
permissions per page range.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ELF = os.path.join(ROOT, "build", "hookhost.elf")
BIN = os.path.join(ROOT, "build", "hookhost.bin")
OUT = os.path.join(ROOT, "device", "hookhost", "hh_payload.h")
PAGE = 0x1000


def objcopy():
    subprocess.run([
        "docker", "run", "--rm",
        "-u", f"{os.getuid()}:{os.getgid()}",
        "-e", "HOME=/tmp",
        "-v", f"{ROOT}:/work", "-w", "/work",
        "devkitpro/devkita64:libnx26",
        "/opt/devkitpro/devkitA64/bin/aarch64-none-elf-objcopy", "-O", "binary",
        "build/hookhost.elf", "build/hookhost.bin",
    ], check=True, stdout=subprocess.DEVNULL)


def sections():
    out = subprocess.run(["llvm-objdump", "-h", ELF], capture_output=True, text=True, check=True).stdout
    secs = {}
    for line in out.splitlines():
        m = re.match(r"\s*\d+\s+(\S+)\s+([0-9a-f]+)\s+([0-9a-f]+)\s+", line)
        if m:
            secs[m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16))
    return secs


def symbols():
    out = subprocess.run(["llvm-objdump", "-t", ELF], capture_output=True, text=True, check=True).stdout
    syms = {}
    for line in out.splitlines():
        parts = line.split()
        if len(parts) >= 6 and re.fullmatch(r"[0-9a-f]+", parts[0]):
            syms[parts[-1]] = int(parts[0], 16)
    return syms


def align(x, a=PAGE):
    return (x + a - 1) & ~(a - 1)


def main():
    if not os.path.exists(ELF):
        sys.exit("build/hookhost.elf missing; run `make device`")
    objcopy()
    secs = sections()
    syms = symbols()
    text_size, text_va = secs[".text"]
    ro_size, ro_va = secs[".rodata"]
    data_size, data_va = secs[".data"]
    bss_size, bss_va = secs[".bss"]

    total = align(bss_va + bss_size)
    file_size = data_va + data_size
    for s in ("hh_exec_tramp", "hh_presence_tramp", "hh_entry_tramp", "hh_runtime"):
        if s not in syms:
            sys.exit(f"missing symbol {s}")

    hdr = f"""/* generated by tools/gen_hh_layout.py - do not edit */
#define HH_PAYLOAD_TEXT_VA      0x{text_va:x}u
#define HH_PAYLOAD_TEXT_SIZE    0x{ro_va - text_va:x}u
#define HH_PAYLOAD_RO_VA        0x{ro_va:x}u
#define HH_PAYLOAD_RO_SIZE      0x{data_va - ro_va:x}u
#define HH_PAYLOAD_DATA_VA      0x{data_va:x}u
#define HH_PAYLOAD_DATA_SIZE    0x{total - data_va:x}u
#define HH_PAYLOAD_TOTAL        0x{total:x}u
#define HH_PAYLOAD_FILE_SIZE    0x{file_size:x}u
#define HH_OFF_EXEC_TRAMP       0x{syms['hh_exec_tramp']:x}u
#define HH_OFF_PRESENCE_TRAMP   0x{syms['hh_presence_tramp']:x}u
#define HH_OFF_ENTRY_TRAMP      0x{syms['hh_entry_tramp']:x}u
#define HH_OFF_RUNTIME          0x{syms['hh_runtime']:x}u
"""
    with open(OUT, "w") as f:
        f.write(hdr)
    print(hdr)
    print(f"bin: {BIN} ({os.path.getsize(BIN)} bytes), total map 0x{total:x}")


if __name__ == "__main__":
    main()
