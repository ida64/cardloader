#!/usr/bin/env python3
"""Emit the kernel-embedded payload + test XCI for mesosphere."""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(os.environ.get("ATMD", "/tmp/atmosphere"),
                   "libraries/libmesosphere/source/kern_hh_data.cpp")
XCI_SIZE = 68096

import re
with open(os.path.join(ROOT, "device", "hookhost", "hh_payload.h")) as f:
    _hdr = f.read()
PAYLOAD_SIZE = int(re.search(r"#define HH_PAYLOAD_TOTAL\s+0x([0-9a-fA-F]+)u", _hdr).group(1), 16)


def emit(name, data, size):
    data = data[:size].ljust(size, b"\0")
    lines = [f"    extern const u8 {name}[0x{size:x}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("        " + ",".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("    };")
    return "\n".join(lines)


def main():
    payload = open(os.path.join(ROOT, "build", "hookhost.bin"), "rb").read()
    xci = open(os.path.join(ROOT, "build", "game.xci"), "rb").read()
    body = [
        "/* generated by tools/gen_kernel_data.py - do not edit */",
        "#include <mesosphere.hpp>",
        "",
        "namespace ams::kern::impl {",
        emit("g_hh_payload", payload, PAYLOAD_SIZE),
        emit("g_hh_xci", xci, XCI_SIZE),
        "}",
        "",
    ]
    with open(OUT, "w") as f:
        f.write("\n".join(body))
    print(f"wrote {OUT}: payload {len(payload)} -> 0x{PAYLOAD_SIZE:x}, xci {len(xci)}")


if __name__ == "__main__":
    main()
